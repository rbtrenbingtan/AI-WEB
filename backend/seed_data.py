def populate_seed(conn):
    from backend.ai.validate_question import validate_question
    stamp=datetime.now(timezone.utc).isoformat()
    sha=hashlib.sha256('\n'.join(PAGES).encode()).hexdigest()
    conn.execute('INSERT INTO documents VALUES (?,?,?,?,?,?,?,?,?,?,?)',('demo',None,1,'数据结构 · 栈与队列（原创示例讲义）',sha,'ready',len(PAGES),SOURCE_NOTE,'[]',None,stamp))
    sentences={}; ordinal=0
    for page,text in enumerate(PAGES,1):
        conn.execute('INSERT INTO pages VALUES (?,?,?)',('demo',page,text))
        ids=[]
        for local,match in enumerate(re.finditer(r'[^\n]+',text)):
            sid=f'demo_p{page:02d}_s{local:02d}'; ordinal+=1
            sentences[(page,local)]=(sid,match.group())
            conn.execute('INSERT INTO sentences VALUES (?,?,?,?,?,?,?)',(sid,'demo',page,ordinal,match.group(),match.start(),match.end()))
            ids.append(sid)
        conn.execute('INSERT INTO chunks VALUES (?,?,?,?,?,?,?)',(f'demo_c{page:02d}','demo',page,ordinal-len(ids)+1,ordinal,text,json.dumps(ids)))
    stems=[]
    for index,(slug,title,description,misconceptions,questions) in enumerate(TOPICS):
        tid='t_'+slug
        pages=[index*2+1,index*2+2]
        conn.execute('INSERT INTO topics VALUES (?,?,?,?,?,?,?,?)',(tid,'demo',title,description,'offline_ai','ready',None,json.dumps([f'demo_c{p:02d}' for p in pages])))
        mids=[]; evidence_by_mid={}
        for code,label,desc,page,local in misconceptions:
            mid='m_'+slug+'_'+code; mids.append(mid)
            sid=sentences[(page,local)][0]; evidence_by_mid[mid]=sid
            refs=[sid]
            conn.execute('INSERT INTO misconceptions VALUES (?,?,?,?,?,?)',(mid,tid,label,desc,json.dumps(refs),'offline_ai_pending_review'))
        for qi,row in enumerate(questions):
            target,stem,correct,*wrong=row; mid=mids[target]
            correct_feedback='该说法符合讲义的操作约定。'+sentences[(misconceptions[target][3],misconceptions[target][4])][1]
            opts=[dict(text=correct,is_correct=True,feedback=correct_feedback)]
            for text in wrong:
                correction=sentences[(misconceptions[target][3],misconceptions[target][4])][1]
                opts.append(dict(text=text,is_correct=False,misconception_id=mid,feedback='该选项所说的“'+text+'”不符合这里的操作约定。本题应当“'+correct+'”。原文：'+correction))
            evidence=[sentences[key][0] for key in EVIDENCE[slug][qi]]
            explanation=sentences[(misconceptions[target][3],misconceptions[target][4])][1]
            if slug=='stack':
                for option,feedback in zip(opts,STACK_FEEDBACK[qi]):
                    option['feedback']=feedback
                explanation=STACK_FEEDBACK[qi][0]
            candidate=dict(stem=stem,options=opts,target_misconception_id=mid,evidence_sentence_ids=evidence,explanation=explanation)
            checked=validate_question(candidate,mids,evidence,stems,target_id=mid)
            if checked['errors']: raise ValueError(f'Seed {slug}/{qi}: '+str(checked['errors']))
            payload=checked['question']; stems.append(stem)
            qid=f'q_{slug}_{qi+1:02d}'; answer=payload['answer_letter']
            conn.execute('INSERT INTO questions VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)',(qid,'demo',tid,'concept',mid,json.dumps(payload,ensure_ascii=False),answer,None,'offline_rule_checked','离线 AI 编写，未进行独立人工审定或在线盲答复核','offline-seed-v2','offline-authoring','bank',SOURCE_NOTE,stamp))

